"""The Mac's in-app updates: Sparkle 2, a Pages appcast, and one controller the app owns.

Nothing here can be compiled on Linux — the shell is an app target — so this pins the contract the
way the other cross-platform guards do, from source:

* the bundle carries all five Sparkle keys, with the exact values the publish signs against;
* the package is wired to `HermesMac` and to nothing else (an iOS target that linked Sparkle would
  be a compile error in CI, since there is no installer to hand the DMG to);
* the controller is started by the app struct, held for the app's lifetime, and reached from the
  menu and from Settings → About through one action;
* the trust anchor stays a *public* key: no secret, no `SUAutomaticallyUpdate=true`, and no feed URL
  or version constant baked into Swift.

The Info.plist is generated by XcodeGen (`info.path` + `properties` in project.yml), so the effective
plist is project.yml's properties unless a generated copy exists on disk; both are read the same way.
"""

from __future__ import annotations

import plistlib
import re
import unittest
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
PROJECT_YML = ROOT / "project.yml"
MAC = ROOT / "Apps" / "HermesMac"

APP = (MAC / "HermesMacApp.swift").read_text(encoding="utf-8")
ABOUT = (MAC / "Views" / "AboutSettingsTab.swift").read_text(encoding="utf-8")
SETTINGS = (MAC / "Views" / "MacSettingsView.swift").read_text(encoding="utf-8")
PROJECT = yaml.safe_load(PROJECT_YML.read_text(encoding="utf-8"))
PROJECT_TEXT = PROJECT_YML.read_text(encoding="utf-8")

FEED_URL = "https://macblizzard.github.io/hermey-downloads/appcast.xml"
# The public half of the one EdDSA keypair. The private half lives outside the tree (CI secret /
# /etc/hermey), and rotating this value breaks update trust for every older build.
PUBLIC_KEY = "ezxgxj3MqbAIuclhB15SoXkIuZzYTkUtKlSB9SeCEGk="

SKIP_DIRS = {".git", ".build", ".venv", "build", "dist", "__pycache__", ".pytest_cache", "node_modules"}
# This file names the shapes it forbids, so it is never a subject of the scan it performs.
SELF = Path(__file__).resolve()


def mac_info() -> dict:
    """The keys XcodeGen will put in `Apps/HermesMac/Info.plist`.

    `info.path` means the file is generated, not committed; when a generated copy is present (after a
    local `xcodegen generate`) it is the truth, otherwise project.yml's `properties` are.
    """
    return PROJECT["targets"]["HermesMac"]["info"]


def effective_info_plist() -> dict:
    path = ROOT / mac_info()["path"]
    if path.is_file():
        with path.open("rb") as handle:
            return plistlib.load(handle)
    return mac_info()["properties"]


def text_files() -> list[Path]:
    """Every text-ish file in the tree, skipping build output and the virtualenvs."""
    return [
        path
        for path in ROOT.rglob("*")
        if path.is_file()
        and not (set(path.parts) & SKIP_DIRS)
        and path.resolve() != SELF
        and path.suffix.lower() in {".swift", ".py", ".yml", ".yaml", ".plist", ".json", ".md", ".txt", ".sh"}
    ]


class TheBundleCarriesTheContract(unittest.TestCase):
    def test_the_plist_is_the_one_this_suite_reads(self) -> None:
        self.assertEqual(mac_info()["path"], "Apps/HermesMac/Info.plist")

    def test_the_feed_is_the_published_appcast(self) -> None:
        # Not a placeholder, not the tailnet address: the Pages appcast is the only feed that a
        # machine outside the tailnet can reach, which is every machine that needs an update.
        self.assertEqual(effective_info_plist()["SUFeedURL"], FEED_URL)

    def test_the_public_key_is_the_one_the_publish_signs_with(self) -> None:
        self.assertEqual(effective_info_plist()["SUPublicEDKey"], PUBLIC_KEY)

    def test_checks_are_enabled_on_a_daily_cycle(self) -> None:
        plist = effective_info_plist()
        self.assertIs(plist["SUEnableAutomaticChecks"], True)
        self.assertEqual(plist["SUScheduledCheckInterval"], 86400)

    def test_installs_are_never_automatic(self) -> None:
        # The prompt is the feature: `SUAutomaticallyUpdate` would replace the app between launches
        # with nothing on screen to cancel, and an unattended swap is the one thing §7.1 forbids.
        self.assertIs(effective_info_plist()["SUAutomaticallyUpdate"], False)

    def test_project_yml_alone_carries_all_five_keys(self) -> None:
        # The generated plist must not be the only place they live: it is git-ignored, so a build
        # from a clean checkout would otherwise ship an app with no feed at all.
        properties = mac_info()["properties"]
        self.assertEqual(properties["SUFeedURL"], FEED_URL)
        self.assertEqual(properties["SUPublicEDKey"], PUBLIC_KEY)
        self.assertIs(properties["SUEnableAutomaticChecks"], True)
        self.assertIs(properties["SUAutomaticallyUpdate"], False)
        self.assertEqual(properties["SUScheduledCheckInterval"], 86400)


class ThePackageIsWiredForTheMacOnly(unittest.TestCase):
    def test_sparkle_is_a_remote_package_at_two_six_or_later(self) -> None:
        package = PROJECT["packages"]["Sparkle"]
        self.assertEqual(package["url"], "https://github.com/sparkle-project/Sparkle")
        # A floor, not a branch: `from` is what makes the resolved Sparkle one the feed's shape.
        self.assertEqual(str(package["from"]), "2.6.0")

    def test_the_mac_target_depends_on_the_sparkle_product(self) -> None:
        dependencies = PROJECT["targets"]["HermesMac"]["dependencies"]
        self.assertIn({"package": "Sparkle", "product": "Sparkle"}, dependencies)

    def test_ios_does_not_link_the_updater(self) -> None:
        # A sideloaded IPA cannot replace itself, so the phone opens a URL instead. Linking Sparkle
        # there would compile an installer nobody may call.
        for name in ("HermesMobile", "HermesMacUITests"):
            dependencies = PROJECT["targets"][name]["dependencies"]
            self.assertNotIn({"package": "Sparkle", "product": "Sparkle"}, dependencies, name)


class TheAppOwnsTheUpdater(unittest.TestCase):
    def test_the_controller_starts_the_updater(self) -> None:
        self.assertIn("SPUStandardUpdaterController(startingUpdater: true", APP)

    def test_the_controller_belongs_to_the_app_struct(self) -> None:
        # Held by the `App`, not by a view: a controller that is re-created when a view is rebuilt
        # forgets its schedule, and the daily check silently stops.
        head = APP.split("var body: some Scene", 1)[0]
        self.assertIn("private let updater: SPUStandardUpdaterController", head)
        self.assertIn("struct HermesMacApp: App {", head)

    def test_the_import_and_the_use_are_both_guarded(self) -> None:
        # A tree built without the package must still compile: the guard is what keeps `xcodegen`
        # output buildable when the dependency cannot be resolved.
        self.assertIn("#if canImport(Sparkle)\nimport Sparkle\n#endif", APP)
        guarded = APP.split("    #if canImport(Sparkle)\n", 1)[1].split("    #endif", 1)[0]
        self.assertIn("private let updater: SPUStandardUpdaterController", guarded)

    def test_one_action_is_shared_by_the_menu_and_settings(self) -> None:
        self.assertIn("private var checkForUpdates: () -> Void {", APP)
        self.assertIn("self.updater.checkForUpdates(nil)", APP)
        self.assertIn("WorkspaceCommands(store: store, checkForUpdates: checkForUpdates, "
                      "shortcuts: store.shortcuts)", APP)
        self.assertIn("MacSettingsView(store: store, checkForUpdates: checkForUpdates)", APP)

    def test_no_installer_of_ours(self) -> None:
        # Sparkle's own driver is the only install path; a second one is a second signature to get
        # wrong.
        for name, source in (("app", APP), ("about", ABOUT)):
            self.assertNotIn("SPUStandardUserDriver", source, name)
            self.assertNotIn("hdiutil", source, name)


class TheDoorIsInBothPlaces(unittest.TestCase):
    def test_the_menu_offers_the_check(self) -> None:
        menu = APP.split("struct WorkspaceCommands: Commands {", 1)[1]
        self.assertIn('Button("Check for Updates…")', menu)
        self.assertIn("checkForUpdates()", menu)
        self.assertIn("let checkForUpdates: () -> Void", menu)

    def test_settings_offers_it_beside_the_version_text(self) -> None:
        # "Next to the current version text" is the whole point: that line is where a person asks
        # which build they are on, so the verb to change it sits under the same label.
        version = ABOUT.index("Text(AppVersion.label)")
        button = ABOUT.index('Button("Check for Updates…")')
        self.assertLess(version, button)
        self.assertIn("checkForUpdates()", ABOUT[button:button + 200])
        self.assertIn(".accessibilityIdentifier(\"aboutCheckForUpdates\")", ABOUT)

    def test_the_settings_window_forwards_the_same_action(self) -> None:
        self.assertIn("let checkForUpdates: () -> Void", SETTINGS)
        self.assertIn(
            "AboutSettingsTab(store: store, checkForUpdates: checkForUpdates)", SETTINGS)

    def test_nothing_is_disabled_behind_the_update(self) -> None:
        for name, source in (("app", APP), ("about", ABOUT), ("settings", SETTINGS)):
            self.assertNotIn("interactiveDismissDisabled", source, name)


class NothingSecretIsInTheTree(unittest.TestCase):
    def test_no_private_key_material(self) -> None:
        # The private half belongs in a CI secret (and, on the publish host, outside the repo):
        # a secret in git is a secret in every clone and in every fork's CI.
        forbidden = [
            re.compile(r"-----BEGIN [A-Z ]*PRIVATE KEY-----"),
            re.compile(r"SPARKLE_ED_PRIVATE_KEY\s*[=:]\s*['\"]?[A-Za-z0-9+/]{16,}"),
            re.compile(r"dsa_priv"),
            # A 64-byte Ed25519 secret in base64 is 88 characters with two padding characters; a
            # public key is 44 and a sha256 is 64 hex, so this shape is a secret and nothing else.
            re.compile(r"(?<![A-Za-z0-9+/])[A-Za-z0-9+/]{86}=="),
        ]
        for pattern in forbidden:
            for path in text_files():
                self.assertIsNone(
                    pattern.search(path.read_text(encoding="utf-8", errors="ignore")),
                    f"{path.relative_to(ROOT)} carries private key material ({pattern.pattern})",
                )

    def test_no_private_key_file(self) -> None:
        interesting = [
            path for path in ROOT.rglob("*")
            if path.is_file()
            and not (set(path.parts) & SKIP_DIRS)
            and (path.suffix.lower() in {".pem", ".key", ".p8", ".p12"}
                 or re.search(r"(private|priv)[-_]?(key|ed25519)", path.name, re.IGNORECASE))
        ]
        self.assertEqual(interesting, [], f"key files in the tree: {interesting}")

    def test_the_public_key_is_the_only_key_quoted(self) -> None:
        # One key, one value: a second (or a truncated) `SUPublicEDKey` anywhere would make the
        # contract above read as satisfied while the app refused every real signature.
        occurrences: set[str] = set()
        pattern = re.compile(r"SUPublicEDKey[\"'=: \t\n]*([A-Za-z0-9+/]{20,}={0,2})")
        for path in text_files():
            occurrences.update(pattern.findall(path.read_text(encoding="utf-8", errors="ignore")))
        self.assertEqual(occurrences, {PUBLIC_KEY})

    def test_no_automatic_install_anywhere(self) -> None:
        for path in text_files():
            text = path.read_text(encoding="utf-8", errors="ignore")
            for match in re.finditer(r"SUAutomaticallyUpdate[^\n]{0,40}", text):
                self.assertNotRegex(
                    match.group(0).lower(),
                    r"(true|yes)\b|<true",
                    f"{path.relative_to(ROOT)} turns silent installs on: {match.group(0)!r}",
                )


class NeitherAppHardCodesTheFeedOrTheBuild(unittest.TestCase):
    def test_the_mac_sources_name_no_feed_host(self) -> None:
        # The feed is read from the bundle's Info.plist, which is the only place it may live on this
        # platform: a literal in Swift would be a second feed to keep in step. (The phone's notifier
        # fetches JSON rather than an appcast, so it keeps its own URLs in HermesAppKit.)
        for path in MAC.rglob("*.swift"):
            self.assertNotIn("macblizzard.github.io", path.read_text(encoding="utf-8"), str(path))

    def test_the_update_surface_holds_no_version_constant(self) -> None:
        for name, source in (("app", APP), ("about", ABOUT)):
            self.assertNotRegex(source, r'"0\.1\.\d+', f"{name} pins a build number")
